export function skinErrorText(error: unknown): string {
  const code = error && typeof error === 'object' && 'code' in error ? String(error.code) : String(error instanceof Error ? error.message : error);
  return Object.hasOwn(skinMessages.messages, code) ? skinT(code as keyof typeof skinMessages.messages) : skinT('failure');
}
